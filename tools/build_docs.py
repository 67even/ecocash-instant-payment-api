def home_contents():
    """The "Where to start" table, in the same form as the other 67even sites."""
    rows = ["## Where to start\n", "| | |", "|:--|:--|"]
    for num in sorted(SECTIONS, key=lambda n: SECTIONS[n][3]):
        if num == 1:
            continue
        _, permalink, title, _, desc = SECTIONS[num]
        rows.append("| [**%s**](%s) | %s |" % (title, permalink.lstrip("/"), BLURBS[num]))
    rows.append("| [**%s**](%s) | %s |" % (REFERENCE_PARENT[2], REFERENCE_PARENT[1].lstrip("/"),
                                           "The portal's own Documentation and SDK tabs, verbatim."))
    return "\n".join(rows) + "\n\n---\n\n## Overview\n"


