#!/usr/bin/env python3
"""Generate the just-the-docs site in docs/ from README.md and reference/.

README.md is the single source of truth. Each numbered `## N. Title` section of
the README becomes one page of the site, so the guide on GitHub and the guide on
GitHub Pages can never drift. CI runs this with --check and fails if they have.

What the transform does to each README section:

  * the `## N. Title` heading becomes the page's single H1 (the page title), and
    every deeper heading moves up one level - so `### 5.1 Charge request`
    becomes `## 5.1 Charge request`, keeping its text and therefore its anchor;
  * image paths (`docs/assets/...`) become `{{ '/assets/...' | relative_url }}`;
  * in-README anchors (`#51-charge-request`) become links to the page that now
    holds that heading (`../api-reference/#51-charge-request`);
  * links to reference/*.md become links to their generated pages, and links to
    repository files (LICENSE, NOTICE) become absolute GitHub URLs.

The three reference files are published verbatim under /reference/, with only
their H1 restated and their image paths rewritten.

Each page keeps its `last_modified_at` while its content is unchanged and only
moves when the content does, so --check is stable. jekyll-sitemap publishes it
as <lastmod> and the structured data as dateModified.

    python3 tools/build_docs.py          # regenerate
    python3 tools/build_docs.py --check  # exit 1 if docs/ is stale (used by CI)
"""

