def build():
    sections = readme_sections()
    missing = set(SECTIONS) - set(sections)
    if missing:
        sys.exit("README.md is missing section(s): %s" % sorted(missing))
    anchors = anchor_map(sections)
    ref_links = {src: permalink for src, _, permalink, _, _, _ in REFERENCES}

    pages = {}
    for num, (fname, permalink, title, order, desc) in SECTIONS.items():
        _, chunk = sections[num]
        body = demote(chunk)
        body = rewrite_links(body, permalink, anchors, ref_links)
        image_slug = "home" if permalink == "/" else permalink.strip("/")
        if num == 1:
            text = HERO + home_contents() + "\n" + body.strip() + "\n"
        else:
            text = "# %s\n\n%s" % (title, body.strip()) + "\n"
        pages[fname] = (front_matter(title, order, permalink, desc, image_slug, "README.md")
                        + text + footer("README.md", "section %d of the README" % num))

    # the reference parent and its children
    fname, permalink, title, order, desc = REFERENCE_PARENT
    items = "\n".join("- [%s](%s)" % (t, rel(permalink, p)) + " - " + d
                      for _, _, p, t, _, d in REFERENCES)
    pages[fname] = (
        front_matter(title, order, permalink, desc, "reference", "reference/", ["has_children: true"])
        + "# %s\n\n" % title
        + "These pages reproduce the EcoCash Developer Portal's own material **as published**, "
          "including its inconsistencies. For the clear, corrected walkthrough, start with the "
          "[guide](../). Where the two differ, see [Known portal issues](../known-issues/).\n\n"
        + items + "\n" + footer("reference/", "the files"))

    for src, fname, permalink, title, order, desc in REFERENCES:
        body = read(os.path.join(ROOT, "reference", src))
        body = re.sub(r"\A#\s+.*?\n+", "", body, count=1)
        body = rewrite_links(body, permalink, {}, ref_links)
        pages[fname] = (
            front_matter(title, order, permalink, desc, permalink.strip("/").replace("/", "-"),
                         "reference/" + src, ["parent: %s" % q(REFERENCE_PARENT[2])])
            + "# %s\n\n" % title + body.rstrip() + "\n"
            + footer("reference/" + src, "the file"))
    return pages


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if docs/ does not match the sources")
    args = ap.parse_args()

    os.makedirs(DOCS, exist_ok=True)
    pages = build()
    today = datetime.date.today().isoformat()
    stale = []
    for name, template in sorted(pages.items()):
        path = os.path.join(DOCS, name)
        current = read(path) if os.path.exists(path) else None
        previous = ""
        if current:
            m = re.search(r"^last_modified_at:\s*(\S+)\s*$", current, re.M)
            previous = m.group(1) if m else ""
        content = template.replace(DATE_TOKEN, previous or today)
        if current == content:
            state = "unchanged"
        else:
            content = template.replace(DATE_TOKEN, today)
            state = "STALE" if args.check else "written"
            stale.append(name)
            if not args.check:
                io.open(path, "w", encoding="utf-8", newline="\n").write(content)
        print("  %-40s %s" % (name, state))

    # a page left behind by a removed section would keep publishing stale content
    generated = set(pages)
    orphans = [f for f in os.listdir(DOCS) if f.endswith(".md") and f not in generated]
    for f in orphans:
        print("  %-40s ORPHAN (not generated - delete it or add it to build_docs.py)" % f)

    if args.check and (stale or orphans):
        print("\ndocs/ is out of date with README.md / reference/: %s" % ", ".join(stale + orphans))
        print("Run: python3 tools/build_docs.py")
        return 1
    print("\n%d page(s), %d changed" % (len(pages), len(stale)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
