def read(path):
    return io.open(path, encoding="utf-8").read().replace("\r\n", "\n")


def q(s):
    return '"%s"' % s.replace("\\", "\\\\").replace('"', '\\"')


def slug(heading):
    """GitHub heading slug - kramdown's GFM parser produces the same ids."""
    s = re.sub(r"<[^>]+>", "", heading).strip().lower()
    s = re.sub(r"[^\w\s-]", "", s)
    return s.replace(" ", "-")


def rel(src_permalink, dst_permalink):
    """Relative URL between two directory-style permalinks."""
    r = posixpath.relpath(dst_permalink, src_permalink)
    return "./" if r == "." else r.rstrip("/") + "/"


def split_code(body):
    """Yield (is_code, text) chunks so transforms never touch fenced code."""
    parts = re.split(r"(^```.*?^```[ \t]*$)", body, flags=re.S | re.M)
    for i, p in enumerate(parts):
        yield (i % 2 == 1, p)


def readme_sections():
    text = read(README)
    heads = [(m.start(), int(m.group(1)), m.group(2))
             for m in re.finditer(r"^## (\d+)\. (.+)$", text, re.M)]
    # ignore any "## N." inside code fences
    fenced = [(m.start(), m.end()) for m in re.finditer(r"^```.*?^```", text, re.S | re.M)]
    heads = [h for h in heads if not any(a <= h[0] < b for a, b in fenced)]
    out = {}
    for i, (pos, num, title) in enumerate(heads):
        end = heads[i + 1][0] if i + 1 < len(heads) else len(text)
        chunk = text[pos:end].rstrip()
        chunk = re.sub(r"\n---\s*$", "", chunk).rstrip()
        out[num] = (title, chunk)
    return out


def anchor_map(sections):
    """README anchor -> (permalink, anchor or None)."""
    m = {}
    for num, (title, chunk) in sections.items():
        permalink = SECTIONS[num][1]
        m[slug("%d. %s" % (num, title))] = (permalink, None)
        body = re.sub(r"^```.*?^```", "", chunk, flags=re.S | re.M)
        for h in re.findall(r"^#{3,6}\s+(.+?)\s*$", body, re.M):
            m[slug(h)] = (permalink, slug(h))
    return m


def rewrite_links(text, self_permalink, anchors, ref_links):
    def link(target):
        if target.startswith(("http://", "https://", "mailto:", "tel:", "{{")):
            return target
        if target.startswith("#"):
            a = target[1:]
            if a in anchors:
                permalink, sub = anchors[a]
                if permalink == self_permalink:
                    return "#" + (sub or "")
                return rel(self_permalink, permalink) + ("#" + sub if sub else "")
            return target
        base, _, frag = target.partition("#")
        name = posixpath.basename(base)
        if base.startswith("reference/") or base.startswith("../reference/") or name in ref_links:
            if name in ref_links:
                return rel(self_permalink, ref_links[name]) + ("#" + frag if frag else "")
        if name in REPO_FILES:
            return "%s/blob/main/%s" % (REPO, name)
        if base.startswith("docs/assets/") or base.startswith("../docs/assets/"):
            return "{{ '%s' | relative_url }}" % base[base.index("/assets/"):]
        repo_path = base.lstrip("./").rstrip("/")
        if repo_path and os.path.exists(os.path.join(ROOT, repo_path)):
            kind = "tree" if os.path.isdir(os.path.join(ROOT, repo_path)) else "blob"
            return "%s/%s/main/%s" % (REPO, kind, repo_path) + ("#" + frag if frag else "")
        return target

    def md(m):
        return "](%s)" % link(m.group(1))

    def html(m):
        return '%s="%s"' % (m.group(1), link(m.group(2)))

    out = []
    for is_code, chunk in split_code(text):
        if not is_code:
            chunk = re.sub(r"\]\(([^)\s]+)\)", md, chunk)
            chunk = re.sub(r'\b(src|href)="([^"]+)"', html, chunk)
        out.append(chunk)
    return "".join(out)


def demote(chunk):
    """Drop the `## N. Title` line and move every deeper heading up one level."""
    chunk = re.sub(r"\A## .*\n+", "", chunk)
    out = []
    for is_code, part in split_code(chunk):
        if not is_code:
            part = re.sub(r"^#(#{2,6}) ", r"\1 ", part, flags=re.M)
        out.append(part)
    return "".join(out)


def front_matter(title, order, permalink, desc, image_slug, source, extra=()):
    fm = ["---", BANNER,
          "title: %s" % q(title),
          "nav_order: %d" % order,
          "permalink: %s" % permalink,
          "description: %s" % q(desc),
          "date: %s" % PUBLISHED,
          "last_modified_at: %s" % DATE_TOKEN,
          "seo:",
          "  type: WebPage",
          "image:",
          "  path: /assets/og/%s.png" % image_slug,
          "  width: 1200",
          "  height: 630",
          "  alt: %s" % q("EcoCash Instant Payment API - " + SITE_NAME if permalink == "/"
                          else "%s - %s" % (title, SITE_NAME)),
          "source_file: %s" % source]
    fm.extend(extra)
    fm.append("---")
    return "\n".join(fm) + "\n\n"


def footer(source, what):
    return ("\n\n---\n\n"
            "This page is generated from %s in "
            "[`%s`](%s/blob/main/%s). "
            "Spotted something wrong? [Open an issue](%s/issues).\n"
            % (what, source, REPO, source, REPO))


